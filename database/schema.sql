-- ============================================================
-- CONVENIENCE VIEW: one row per design with all four forms
-- (handy for the "My Designs" page and for building reports)
-- ============================================================

CREATE VIEW design_full AS
SELECT
    d.id, d.user_id, d.design_no, d.design_name, d.design_date,
    d.phase, d.wire_type, d.mechanical_component,
    d.status, d.current_step, d.created_at, d.updated_at,

    m.connection, m.voltage, m.power, m.hp, m.frequency, m.rpm, m.pole, m.uph, m.capacitor,

    s.material, s.stamping_material, s.n, s.y, s.w, s.w2, s.a1, s.shape,
    s.a, s.b, s.c, s.d, s.e, s.dw, s.d0, s.dia, s.lf_y, s.lf_t,

    r.m, r.rng_wt, r.rng_ht, r.x, r.v, r.v2, r.a2,
    r.ra, r.rb, r.rc, r.rd, r.re, r.rw, r.shaft_diameter,

    wd.current_density, wd.efficiency, wd.insulation_dia, wd.actual_use_dia, wd.final_turns,
    wd.insulation_dia_aux, wd.actual_use_dia_aux, wd.final_turns_aux, wd.final_stack_length
FROM designs d
LEFT JOIN design_main_data     m  ON m.design_id  = d.id
LEFT JOIN design_stamping_data s  ON s.design_id  = d.id
LEFT JOIN design_rotor_data    r  ON r.design_id  = d.id
LEFT JOIN design_winding_data  wd ON wd.design_id = d.id;


